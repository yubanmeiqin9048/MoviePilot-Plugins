"""Vue 联邦构建与安全投影契约测试。"""

from __future__ import annotations

from pathlib import Path

PLUGIN_ROOT = Path(__file__).resolve().parents[1]


def test_federation_exposes_only_config_and_safe_page_components() -> None:
    """Vite 暴露配置入口和安全占位 Page，不暴露额外宿主入口。"""

    source = (PLUGIN_ROOT / "frontend" / "vite.config.ts").read_text(encoding="utf-8")
    assert "name: 'Alist2Strm'" in source
    assert "'./Config': './src/components/Config.vue'" in source
    assert "'./Page': './src/components/Page.vue'" in source
    assert "./AppPage" not in source


def test_config_uses_injected_api_and_keeps_failed_draft_without_host_save_event() -> None:
    """配置组件必须通过注入 API 保存，失败时保留草稿且不触发宿主二次保存。"""

    source = (PLUGIN_ROOT / "frontend" / "src" / "components" / "Config.vue").read_text(encoding="utf-8")
    assert "saveConfiguration(props.api" in source
    assert "emit('save')" not in source
    assert "saveError.value = getErrorMessage" in source
    assert 'type="password"' in source
    assert "MoviePilotAPI" not in source
    assert "完整扫描成功后，会清理该目录中不再需要的受管文件，包括手工放入的文件；请使用专用输出目录。" in source


def test_page_runs_saved_all_or_one_mapping_and_stops_status_polling_on_close() -> None:
    """详情页只通过注入 API 运行已保存配置，并在卸载时停止轮询。"""

    source = (PLUGIN_ROOT / "frontend" / "src" / "components" / "Page.vue").read_text(encoding="utf-8")
    assert "startScan(props.api" in source
    assert "startMappingScan(props.api" in source
    assert "configurationEditorState.dirty" in source
    assert "setInterval" in source and "}, 2000)" in source
    assert "onUnmounted(()" in source
    assert "stopPolling()" in source
    assert "clearInterval" in source
    for counter in ("generated", "downloaded", "updated", "skipped", "deleted", "failed"):
        assert counter in source
    assert "emit('save')" not in source


def test_built_federation_assets_are_delivered_and_reference_both_exposes() -> None:
    """构建后的 remoteEntry 与 Config/Page 产物必须同时存在。"""

    assets = PLUGIN_ROOT / "frontend" / "dist" / "assets"
    remote_entry = assets / "remoteEntry.js"
    assert remote_entry.is_file()
    content = remote_entry.read_text(encoding="utf-8")
    assert "__federation_expose_Config" in content
    assert "__federation_expose_Page" in content
    assert any(path.name.startswith("__federation_expose_Config") for path in assets.glob("*.js"))
    assert any(path.name.startswith("__federation_expose_Page") for path in assets.glob("*.js"))


def test_frontend_package_has_reproducible_lockfile() -> None:
    """前端依赖锁文件存在，避免宿主加载缺失资产。"""

    lockfile = PLUGIN_ROOT / "frontend" / "yarn.lock"
    assert lockfile.is_file()
    assert lockfile.read_text(encoding="utf-8").startswith("# THIS IS AN AUTOGENERATED FILE")
